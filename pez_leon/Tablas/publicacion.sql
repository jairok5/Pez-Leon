CREATE TABLE publicacion (
  publicacion_id             INT UNSIGNED      NOT NULL AUTO_INCREMENT,
  eid                        VARCHAR(30)       NOT NULL COMMENT 'Identificador único de Scopus',
  doi                        VARCHAR(255)      NULL,
  titulo                     VARCHAR(500)      NOT NULL,
  anio                       SMALLINT UNSIGNED NOT NULL,
  fuente_id                  SMALLINT UNSIGNED NOT NULL,
  editorial_id               SMALLINT UNSIGNED NULL COMMENT 'Editorial del registro (puede cambiar en el tiempo para una misma revista)',
  tipo_documento_id          TINYINT UNSIGNED  NOT NULL,
  volumen                    VARCHAR(20)       NULL,
  numero                     VARCHAR(20)       NULL,
  num_articulo               VARCHAR(20)       NULL,
  pagina_inicio              VARCHAR(10)       NULL,
  pagina_fin                 VARCHAR(10)       NULL,
  citas                      INT UNSIGNED      NOT NULL DEFAULT 0 COMMENT 'Citas en Scopus al momento de la exportación',
  acceso_abierto             BOOLEAN           NOT NULL DEFAULT 0 COMMENT '1 = Scopus lo marca como All Open Access',
  etapa_publicacion          VARCHAR(30)       NOT NULL DEFAULT 'Final',
  pubmed_id                  VARCHAR(20)       NULL,
  editores                   VARCHAR(500)      NULL,
  resumen                    TEXT              NULL,
  direccion_correspondencia  TEXT              NULL COMMENT 'Incluye correos personales: no mostrar en reportes',
  enlace_scopus              VARCHAR(500)      NULL,
  carga_id                   INT UNSIGNED      NOT NULL,
  PRIMARY KEY (publicacion_id),
  UNIQUE KEY uq_publicacion_eid (eid),
  KEY idx_publicacion_anio (anio),
  KEY idx_publicacion_citas (citas),
  KEY idx_publicacion_doi (doi),
  KEY idx_publicacion_fuente (fuente_id),
  KEY idx_publicacion_editorial (editorial_id),
  KEY idx_publicacion_tipo (tipo_documento_id),
  KEY idx_publicacion_carga (carga_id),
  FULLTEXT KEY ft_publicacion_texto (titulo, resumen),
  CONSTRAINT chk_publicacion_anio CHECK (anio BETWEEN 1800 AND 2100),
  CONSTRAINT fk_publicacion_fuente    FOREIGN KEY (fuente_id)         REFERENCES fuente (fuente_id),
  CONSTRAINT fk_publicacion_editorial FOREIGN KEY (editorial_id)      REFERENCES editorial (editorial_id),
  CONSTRAINT fk_publicacion_tipo      FOREIGN KEY (tipo_documento_id) REFERENCES tipo_documento (tipo_documento_id),
  CONSTRAINT fk_publicacion_carga     FOREIGN KEY (carga_id)          REFERENCES carga (carga_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Un registro por documento exportado de Scopus';
  
